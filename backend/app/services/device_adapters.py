from abc import ABC, abstractmethod

class DeviceAdapter(ABC):
    """Interface contract only. No physical adapter is currently implemented."""
    @abstractmethod
    def identify_device(self): ...
    @abstractmethod
    def read_capabilities(self): ...
    @abstractmethod
    def authenticate(self, authorization): ...
    @abstractmethod
    def read_security_configuration(self): ...
    @abstractmethod
    def change_credential(self, credential_reference): ...
    @abstractmethod
    def verify_credential_change(self): ...
    @abstractmethod
    def disconnect(self): ...
    @abstractmethod
    def get_adapter_status(self): ...
